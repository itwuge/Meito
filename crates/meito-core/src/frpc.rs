// ===== 内部工具 =====

/// 按出现顺序保存 key=value；键唯一性由调用方检查。
#[derive(Debug, Default)]
struct KeyValues {
    entries: Vec<(String, String)>,
}

impl KeyValues {
    /// 插入键值；若键已存在则返回旧值，便于调用方判定重复。
    ///
    /// # 参数
    /// - `key`: 已归一化为小写的键。
    /// - `value`: 原始值。
    ///
    /// # 错误
    /// 不返回错误。
    fn insert(&mut self, key: String, value: String) -> Option<String> {
        if let Some(existing) = self
            .entries
            .iter_mut()
            .find(|(existing_key, _)| existing_key == &key)
        {
            return Some(std::mem::replace(&mut existing.1, value));
        }
        self.entries.push((key, value));
        None
    }

    /// 按键查找值。
    ///
    /// # 参数
    /// - `key`: 小写键名。
    ///
    /// # 错误
    /// 不返回错误；缺失返回 `None`。
    fn get(&self, key: &str) -> Option<&String> {
        self.entries
            .iter()
            .find(|(existing_key, _)| existing_key == key)
            .map(|(_, value)| value)
    }

    /// 判断键是否存在。
    ///
    /// # 参数
    /// - `key`: 小写键名。
    ///
    /// # 错误
    /// 不返回错误。
    fn contains(&self, key: &str) -> bool {
        self.get(key).is_some()
    }

    /// 判断是否为空。
    ///
    /// # 参数
    /// - 无（仅 `&self`）。
    ///
    /// # 错误
    /// 不返回错误。
    fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}

/// 判断输入是否为合法 frps 主机名（渲染前校验）。
///
/// # 参数
/// - `value`: 主机名或地址。
///
/// # 错误
/// 不返回错误；非法返回 `false`。
fn valid_host(value: &str) -> bool {
    if value.is_empty() || value.len() > 255 {
        return false;
    }
    value
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_' | ':'))
}

/// 审计用主机名校验；与渲染前规则一致。
///
/// # 参数
/// - `value`: `[common] server_addr` 的取值。
///
/// # 错误
/// 不返回错误；非法返回 `false`。
fn valid_host_display(value: &str) -> bool {
    valid_host(value)
}

/// 判断地址是否为回环。
///
/// # 参数
/// - `value`: IP 字面量（本契约只接受 IP，不接受主机名）。
///
/// # 错误
/// 不返回错误；非回环或无法解析返回 `false`。
fn is_loopback(value: &str) -> bool {
    value
        .parse::<IpAddr>()
        .map(|address| address.is_loopback())
        .unwrap_or(false)
}

/// 校验 secret_key 字符集与长度。
///
/// # 参数
/// - `value`: secret_key 字符串。
///
/// # 错误
/// 不返回错误；非法返回 `false`。
fn valid_secret(value: &str) -> bool {
    let length = value.chars().count();
    (SECRET_MIN_CHARS..=SECRET_MAX_CHARS).contains(&length) && value.chars().all(secret_char)
}

/// 判断字符是否属于 base64url 无填充字符集。
///
/// # 参数
/// - `value`: 单个字符。
///
/// # 错误
/// 不返回错误；非法返回 `false`。
fn secret_char(value: char) -> bool {
    value.is_ascii_alphanumeric() || value == '_' || value == '-'
}

/// 构造参数错误。
///
/// # 参数
/// - `message`: 具体原因。
///
/// # 错误
/// 不返回错误；返回已构造的 `E_USAGE`。
fn usage_error(message: impl std::fmt::Display) -> MeitoError {
    MeitoError::new(ErrorCode::Usage, message.to_string())
}

/// 构造 P2P 错误。
///
/// # 参数
/// - `message`: 具体原因。
///
/// # 错误
/// 不返回错误；返回已构造的 `E_P2P_XTCP`。
fn p2p_error(message: impl std::fmt::Display) -> MeitoError {
    MeitoError::new(ErrorCode::P2pXtcp, message.to_string())
}
