//! File: frpc xtcp visitor 配置渲染与禁中继审计（M4-1）。
//!
//! 仅允许 frp `xtcp` 直连模式：visitor 绑定回环，数据由 UDP 直连承载。
//! 任何 `stcp`、`fallbackTo`、`fallback` 一类中继回落都必须被拒绝（`E_P2P_XTCP`，
//! 退出码 6），避免字节回流服务器。
//!
//! 契约缺口：frp 拓扑目前没有独立的机器可读契约；回环地址与端口仍由调用方从
//! `contracts/entry.json` 读取后传入，本模块不写死任何端口数值。

use std::net::IpAddr;

use crate::error::{ErrorCode, MeitoError};
use crate::log::is_uuid_v4;

// ===== 协议常量（协议名，不是数值契约） =====

/// 唯一允许的 frp 代理类型。
const PROXY_TYPE_XTCP: &str = "xtcp";

/// visitor 角色。
const ROLE_VISITOR: &str = "visitor";

/// 代理名前缀；完整名称为 `ssh-<session_id>`。
const NAME_PREFIX: &str = "ssh-";

/// common 段固定节名。
const COMMON_SECTION: &str = "common";

/// secret_key 最短长度；低于该长度视为配置错误。
const SECRET_MIN_CHARS: usize = 16;

/// secret_key 最长长度；超过该长度视为配置错误。
const SECRET_MAX_CHARS: usize = 128;

/// 审计时必须存在的代理字段。
const REQUIRED_PROXY_KEYS: [&str; 6] = [
    "type",
    "role",
    "server_name",
    "secret_key",
    "bind_addr",
    "bind_port",
];

/// 审计时禁止出现的键名（小写）；命中即判定为可能的中继回落。
const FORBIDDEN_KEYS: [&str; 5] = [
    "fallbackto",
    "fallback",
    "fallback_to",
    "stcp",
    "allow_relay",
];

// ===== 输入 =====

/// 渲染 visitor 配置所需的输入。
///
/// `bind_addr` 必须由调用方从 `contracts/entry.json` 读取；本模块只做回环校验，
/// 不内置地址字面量。`bind_port=0` 表示由系统分配临时端口，真实 frpc 行为尚未实测。
#[derive(Debug, Clone, Copy)]
pub struct FrpcVisitorSpec<'a> {
    /// 会话 id；必须是 UUID v4，并与 `server_name` 绑定。
    pub session_id: &'a str,
    /// frps 主机名或地址，不含端口。
    pub server_addr: &'a str,
    /// frps 监听端口，必须来自调用方配置。
    pub server_port: u16,
    /// 每会话 secret_key，base64url 字符集。
    pub secret_key: &'a str,
    /// visitor 本地绑定地址；必须是回环地址。
    pub bind_addr: &'a str,
    /// visitor 本地绑定端口；0 表示系统分配。
    pub bind_port: u16,
}

// ===== 渲染 =====

/// 渲染 frpc 的 INI 配置文本。
///
/// # 参数
/// - `spec`: 会话、frps 地址与回环绑定参数。
///
/// # 错误
/// 参数格式非法返回 `E_USAGE`（退出码 2）；绑定非回环返回 `E_P2P_XTCP`（退出码 6）。
pub fn render_visitor_ini(spec: &FrpcVisitorSpec<'_>) -> Result<String, MeitoError> {
    if !is_uuid_v4(spec.session_id) {
        return Err(usage_error("session_id 必须是 UUID v4"));
    }
    if !valid_host(spec.server_addr) {
        return Err(usage_error(
            "frps 主机名非法：不得为空、不得含空白或配置注入字符",
        ));
    }
    if spec.server_port == 0 {
        return Err(usage_error("frps 端口必须在 1..=65535"));
    }
    if !valid_secret(spec.secret_key) {
        return Err(usage_error("secret_key 必须是 16..=128 位 base64url 字符"));
    }
    if !is_loopback(spec.bind_addr) {
        return Err(p2p_error(format!(
            "visitor bind_addr 必须是回环地址，收到 {}",
            spec.bind_addr
        )));
    }

    let server_name = format!("{NAME_PREFIX}{}", spec.session_id);
    Ok(format!(
        "# generated by meito; do not edit\n[common]\nserver_addr = {}\nserver_port = {}\n\n[{}]\ntype = {}\nrole = {}\nserver_name = {}\nsecret_key = {}\nbind_addr = {}\nbind_port = {}\n",
        spec.server_addr,
        spec.server_port,
        server_name,
        PROXY_TYPE_XTCP,
        ROLE_VISITOR,
        server_name,
        spec.secret_key,
        spec.bind_addr,
        spec.bind_port
    ))
}

// ===== 审计 =====

/// 审计已渲染的 visitor 配置，拒绝任何中继回落或非回环绑定。
///
/// # 参数
/// - `text`: 待审计的 INI 文本，通常是 [`render_visitor_ini`] 的输出，也可来自磁盘。
///
/// # 错误
/// 命中禁项、缺少字段、字段值非法或出现重复键时返回 `E_P2P_XTCP`（退出码 6）。
pub fn audit_visitor_ini(text: &str) -> Result<(), MeitoError> {
    let mut common = KeyValues::default();
    let mut proxy = KeyValues::default();
    let mut section = String::new();

    for (index, raw_line) in text.lines().enumerate() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }
        if line.starts_with('[') {
            if !line.ends_with(']') {
                return Err(p2p_error(format!("第 {} 行节头未闭合", index + 1)));
            }
            section = line[1..line.len() - 1].trim().to_string();
            if section.is_empty() {
                return Err(p2p_error(format!("第 {} 行节名为空", index + 1)));
            }
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(p2p_error(format!("第 {} 行不是 key=value", index + 1)));
        };
        let key = key.trim().to_ascii_lowercase();
        let value = value.trim().to_string();
        if key.is_empty() {
            return Err(p2p_error(format!("第 {} 行键名为空", index + 1)));
        }
        if FORBIDDEN_KEYS.contains(&key.as_str())
            || key.contains("fallback")
            || value.eq_ignore_ascii_case("stcp")
        {
            return Err(p2p_error(format!(
                "检测到中继回落配置 {key}={value}；只允许 xtcp 直连"
            )));
        }
        let target = if section == COMMON_SECTION {
            &mut common
        } else if section.starts_with(NAME_PREFIX) {
            &mut proxy
        } else {
            return Err(p2p_error(format!(
                "未知节 {section}；只允许 [common] 与 [ssh-<session>]"
            )));
        };
        if target.insert(key.clone(), value).is_some() {
            return Err(p2p_error(format!("重复键：{key}")));
        }
    }

    if proxy.is_empty() {
        return Err(p2p_error("缺少 [ssh-<session>] 节"));
    }
    for key in REQUIRED_PROXY_KEYS {
        if !proxy.contains(key) {
            return Err(p2p_error(format!("缺少必需字段 {key}")));
        }
    }
    if proxy.get("type").map(String::as_str) != Some(PROXY_TYPE_XTCP) {
        return Err(p2p_error("type 必须为 xtcp"));
    }
    if proxy.get("role").map(String::as_str) != Some(ROLE_VISITOR) {
        return Err(p2p_error("role 必须为 visitor"));
    }
    let session_name = proxy.get("server_name").map(String::as_str).unwrap_or("");
    let server_name_ok = session_name
        .strip_prefix(NAME_PREFIX)
        .is_some_and(is_uuid_v4);
    if !server_name_ok {
        return Err(p2p_error("server_name 必须为 ssh-<UUID v4> 且与会话绑定"));
    }
    let bind_addr = proxy.get("bind_addr").map(String::as_str).unwrap_or("");
    if !is_loopback(bind_addr) {
        return Err(p2p_error("bind_addr 必须是回环地址"));
    }
    let bind_port = proxy
        .get("bind_port")
        .and_then(|value| value.parse::<u32>().ok())
        .filter(|value| *value <= 65535);
    if bind_port.is_none() {
        return Err(p2p_error("bind_port 必须是 0..=65535 的整数"));
    }
    if !valid_secret(proxy.get("secret_key").map(String::as_str).unwrap_or("")) {
        return Err(p2p_error("secret_key 缺失或格式非法"));
    }
    if !common.contains("server_addr") || !common.contains("server_port") {
        return Err(p2p_error("缺少 [common] server_addr/server_port"));
    }
    if !valid_host_display(common.get("server_addr").map(String::as_str).unwrap_or("")) {
        return Err(p2p_error("server_addr 非法"));
    }
    if common
        .get("server_port")
        .and_then(|value| value.parse::<u32>().ok())
        .filter(|value| (1..=65535).contains(value))
        .is_none()
    {
        return Err(p2p_error("server_port 必须在 1..=65535"));
    }
    Ok(())
}

